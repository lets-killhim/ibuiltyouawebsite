// Turns prompts/*.md into functions/_lib/prompts.js so the functions can import them. Run after editing a prompt.
import fs from 'node:fs';
const read = (f) => fs.readFileSync(new URL(`../prompts/${f}`, import.meta.url), 'utf8').trim() + '\n';
const presets = [
  ['remodel', 'remodel.md'],
  ['restaurant bold casual', 'restaurant-bold.md'],
  ['restaurant elegant minimal', 'restaurant-minimal.md'],
  ['restaurant hole in the wall', 'restaurant-hole.md'],
];
const out = `// Generated by scripts/build-prompts.mjs from prompts/*.md. Edit the markdown, then: node scripts/build-prompts.mjs
export const DESIGN_CORE = ${JSON.stringify(read('core.md'))};
export const PRESETS = ${JSON.stringify(presets.map(([name, f]) => ({ name, prompt: read(f) })), null, 0)};
`;
fs.writeFileSync(new URL('../functions/_lib/prompts.js', import.meta.url), out);
console.log('wrote functions/_lib/prompts.js:', presets.map(([n, f]) => `${n} ~${Math.round(read(f).length / 4)} tok`).join(', '), `| core ~${Math.round(read('core.md').length / 4)} tok`);
